    private static var localized: [String: String] {
        let stored = UserDefaults.standard.string(forKey: "app_language") ?? "zh"
        let code: String
        if stored == "system" {
            code = (Locale.preferredLanguages.first ?? "en").hasPrefix("zh") ? "zh" : "en"
        } else {
            code = stored
        }
        return code == "en" ? en : zh
    }

